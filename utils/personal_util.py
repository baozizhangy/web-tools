def compute_check_digit(bank_card_number):
    # 补充0以保持统一的长度
    bank_card_number += '0'

    # 根据Luhn算法计算校验数字
    total_sum = sum(int(digit) if i % 2 == 0 else int(digit) * 2 // 10 + int(digit) * 2 % 10
                    for i, digit in enumerate(bank_card_number[::-1]))
    check_digit = (10 - total_sum % 10) % 10

    return check_digit


